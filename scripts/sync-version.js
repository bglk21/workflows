// Writes package.json's version into public/js/version.js so the browser
// (including the static GitHub Pages build) can show it. Runs automatically
// via the "version" npm script after `npm version <patch|minor|major>`.
import { readFile, writeFile } from 'node:fs/promises';

const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const out = new URL('../public/js/version.js', import.meta.url);
await writeFile(out, `// Generated by scripts/sync-version.js from package.json. Do not edit.\nexport const VERSION = '${pkg.version}';\n`);
console.log(`public/js/version.js -> ${pkg.version}`);
